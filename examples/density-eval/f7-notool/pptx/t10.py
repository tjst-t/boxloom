from kit_t06_t10 import *

d = Deck("留学生の生活の支え 来年度の施策")
d.cover("留学生の生活の支え:来年度の3つの施策", "困りごとの上位に施策を当て、年1,000万円の枠に収める",
        "学生支援の委員会", "決めたいこと:来年度の3つの施策と予算(2月に決定)")

# 1. 現状
s = d.content("困りごとの上位は住まい探し48%と日本語の手続き44%",
              "留学生380人(学部140・大学院240)、出身は32の国と地域。困りごとを複数回答で聞いた。",
              source="留学生の調べ(回答211)")
text(s, M, 1.95, 7.3, 0.4, [("困りごと(回答211、複数回答)", 15, True, NAVY)])
bar_chart(s, M, 2.35, 7.3, 4.3, ["住まい探し", "日本語の手続き", "アルバイト探し", "孤立", "病院"],
          [48, 44, 31, 27, 22], horizontal=True, highlight=(0, 1), maxv=58, size=14)
x2, w2 = 8.5, W - M - 8.5
stat(s, x2, 2.0, w2, "14人", "去年、退学・休学した留学生", color=ACCENT, nsize=34)
stat(s, x2, 3.4, w2, "6人", "そのうち理由が経済の人(理由の1位)", nsize=34)
text(s, x2, 4.85, w2, 1.8, [
    [("暮らしの困りごとが、学びを続けられるかに響いている。", 14, True, INK)],
    [("住まい・手続き・孤立を、来年度の施策で支える。", 14, False, INK)],
], space=6)

# 2. 困りごとと施策
s = d.content("住まい・手続き・孤立に、施策を1つずつ当てる",
              "大学の寮は120室で、空き待ちが64人。民間の部屋を借りるときに保証人がいない人が37%。")
rows = [
    ("住まい探し 48%", "施策1 大学が保証人の代わりになる制度",
     "保証人がいない37%の人も民間の部屋を借りられる。寮の空き待ち64人の受け皿にもなる", "年300万円の積み立て"),
    ("日本語の手続き 44%", "施策3 手続きの付き添いの窓口",
     "役所・銀行・病院などの手続きに職員が付き添う。病院の困りごと(22%)にも効く", "職員1名 年520万円"),
    ("孤立 27%", "施策2 日本人学生の相棒(バディ)",
     "留学生1人ずつに日本人学生を1人付ける。生活の相談相手になる", "謝礼 年450万円"),
]
y = 2.0
for need, plan, why, cost in rows:
    rect(s, M, y, 2.6, 1.45, NAVY)
    text(s, M + 0.15, y, 2.3, 1.45, [(need, 16, True, WHITE)], anchor=MSO_ANCHOR.MIDDLE)
    rect(s, M + 2.6, y, W - 2 * M - 2.6, 1.45, LIGHT)
    text(s, M + 2.8, y + 0.1, 6.6, 0.45, [(plan, 16, True, NAVY)])
    text(s, M + 2.8, y + 0.55, 6.6, 0.85, [(why, 13, False, INK)])
    text(s, M + 9.6, y, W - 2 * M - 9.6 - 0.15, 1.45, [(cost, 14, True, ACCENT)],
         anchor=MSO_ANCHOR.MIDDLE, align=PP_ALIGN.RIGHT)
    y += 1.6

# 3. 予算と日程
s = d.content("3つを全部行うと年1,270万円で、枠を270万円超える",
              "予算の枠は年1,000万円。どれを削るか、どれを小さく始めるかを決めたい。")
text(s, M, 1.95, 6.2, 0.4, [("施策の費用(年、万円)", 15, True, NAVY)])
table(s, M, 2.4, 6.2, 2.4, [
    ["施策", "年の費用"],
    ["施策1 保証人の代わり(積み立て)", "300万円"],
    ["施策2 相棒(バディ)の謝礼", "450万円"],
    ["施策3 付き添いの窓口(職員1名)", "520万円"],
    ["合計(枠 1,000万円)", "1,270万円"],
], [4.4, 1.8], size=14, emph_rows=(4,), align_right=(1,))
text(s, M, 5.05, 6.2, 0.4, [("枠に収める組み方の例", 15, True, NAVY)])
bullets(s, M, 5.45, 6.2, 1.35, [
    "施策2の謝礼を450万円から180万円に減らし、相棒を付ける人を絞る",
    "2つの施策だけにする(施策1+施策3 で820万円)",
], size=13, space=4)
x2, w2 = 7.4, W - M - 7.4
text(s, x2, 1.95, w2, 0.4, [("日程", 15, True, NAVY)])
steps = [("2月", "施策と予算を決める(この委員会)"), ("4月", "施策を始める"), ("10月", "中間の調べ(困りごとを聞き直す)")]
yy = 2.4
for i, (when, what) in enumerate(steps):
    rect(s, x2, yy, 1.2, 1.0, NAVY if i < 2 else ACCENT)
    text(s, x2, yy, 1.2, 1.0, [(when, 18, True, WHITE)], align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    rect(s, x2 + 1.2, yy, w2 - 1.2, 1.0, LIGHT)
    text(s, x2 + 1.35, yy, w2 - 1.5, 1.0, [(what, 14, False, INK)], anchor=MSO_ANCHOR.MIDDLE)
    yy += 1.15
text(s, x2, 5.95, w2, 0.8, [("中間の調べで困りごとの割合と退学・休学の数を見て、再来年度の配分を見直す", 13, False, MUTED)])
d.save()
