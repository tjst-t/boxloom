# 3. 日程と懸念
s = d.content("7月の発売に向け、納期12週の弁を早めに押さえる",
              "夏の需要に合わせて7月に出す。遅れると発売は9月になり、夏を逃す。")
text(s, M, 1.95, W - 2 * M, 0.4, [("日程", 15, True, NAVY)])
steps = [("3月", "量産の試作"), ("5月", "品質の確認"), ("7月", "発売(夏の需要)")]
sw = (W - 2 * M) / 3
for i, (when, what) in enumerate(steps):
    rect(s, M + i * sw, 2.4, sw - 0.05, 1.0, NAVY if i < 2 else ACCENT,
         shape=MSO_SHAPE.CHEVRON if i else MSO_SHAPE.PENTAGON)
    text(s, M + i * sw + 0.45, 2.45, sw - 0.9, 0.9,
         [(when, 17, True, WHITE), (what, 13, False, WHITE)], anchor=MSO_ANCHOR.MIDDLE)
text(s, M, 3.5, W - 2 * M, 0.4, [("遅れたときは9月に発売", 13, False, MUTED)], align=PP_ALIGN.RIGHT)
cw = (W - 2 * M - 0.3) / 2
card(s, M, 4.0, cw, 2.75, "懸念:弁の取引先が1社だけ",
     ["部品の弁は1社からしか買えず、納期は12週",
      "その1社が遅れると、7月の発売が9月にずれる"], size=14, bar=ACCENT)
card(s, M + cw + 0.3, 4.0, cw, 2.75, "手当て(案)",
     ["量産の分の弁は、品質の確認(5月)を待たずに発注を決める",
      "2社目の取引先を並行して探す"], size=14)
d.save()
