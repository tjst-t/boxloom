from kit_t06_t10 import *

d = Deck("外来の待ち時間の短縮")
d.cover("外来の待ち時間を短くする3つの手", "内科の待ちを2年で60分以下へ",
        "病院 運営会議", "決めたいこと:待ち時間を短くする3つの手を進めるか")

# 1. 現状
s = d.content("受付から診察までの待ちは平均68分。内科は92分と最も長い",
              "外来は1日平均820人。患者の不満の1位も待ち時間(58%)。", source="患者の調べ(回答640)")
text(s, M, 1.95, 7.0, 0.4, [("受付から診察までの待ち(平均、分)", 15, True, NAVY)])
bar_chart(s, M, 2.35, 7.0, 4.3, ["内科", "整形外科", "小児科", "全体"], [92, 74, 41, 68], fmt='0"分"',
          highlight=(0,), maxv=105, size=14)
x2, w2 = 8.2, W - M - 8.2
text(s, x2, 1.95, w2, 0.4, [("2年の目標", 15, True, NAVY)])
stat(s, x2, 2.4, w2, "92分 → 60分以下", "内科(32分以上短くする)", color=ACCENT, nsize=28)
stat(s, x2, 3.75, w2, "68分 → 50分以下", "全体(18分以上短くする)", nsize=28)
text(s, x2, 5.15, w2, 0.4, [("患者の不満(回答640)", 15, True, NAVY)])
bullets(s, x2, 5.55, w2, 1.2, ["1位 待ち時間 58%", "2位 待つ場所が混む 21%"], size=14, space=3)

# 2. 内科の内訳
s = d.content("内科の待ちの過半は診察の前。予約どおりに始まるのは31%",
              "内科の待ちを場所ごとに分けた(重なりがあるので合計は92分にならない)。")
text(s, M, 1.95, 6.6, 0.4, [("内科の待ちの内訳(分)", 15, True, NAVY)])
bar_chart(s, M, 2.35, 6.6, 4.3, ["受付", "検査", "診察の前", "会計"], [8, 26, 52, 18], fmt='0"分"',
          horizontal=True, highlight=(2,), maxv=62, size=14)
x2, w2 = 7.6, W - M - 7.6
stat(s, x2, 2.0, w2, "54%", "予約で来る患者の割合", nsize=32)
stat(s, x2, 3.4, w2, "31%", "予約の時刻どおりに診察が始まった割合", color=ACCENT, nsize=32)
text(s, x2, 4.85, w2, 1.9, [
    [("予約の患者の多くも、診察の前で待っている。", 14, True, INK)],
    [("検査の結果を待ってから診察に入るため、検査(26分)の遅れが診察の前の待ち(52分)に重なると見られる。", 14, False, INK)],
], space=6)

# 3. 3つの手
s = d.content("3つの手:検査を先に、会計は機械で、呼び出しは手元へ",
              "待ちの長い場所に1つずつ当てる。費用は案2・案3の分。")
cw = (W - 2 * M - 0.6) / 3
items = [
    ("案1 検査を先に受ける流れ", "効く所:検査 26分・診察の前 52分",
     ["予約の前日に検査の時刻を知らせ、診察の前に検査を済ませておく", "費用:材料に試算なし"]),
    ("案2 会計の自動精算機", "効く所:会計 18分",
     ["自動精算機を4台置く", "費用:1台600万円 × 4台 = 2,400万円", "会計の職員6人の仕事の一部を移せる"]),
    ("案3 呼び出しをスマートフォンに", "効く所:待つ場所の混み(不満の2位)",
     ["診察の順が近づいたらスマートフォンに知らせ、院内で待たなくてよくする", "費用:年240万円"]),
]
for i, (head, where, body) in enumerate(items):
    x = M + i * (cw + 0.3)
    rect(s, x, 2.0, cw, 4.75, LIGHT)
    rect(s, x, 2.0, cw, 0.08, NAVY if i else ACCENT)
    text(s, x + 0.2, 2.2, cw - 0.4, 0.8, [(head, 17, True, NAVY)])
    text(s, x + 0.2, 3.05, cw - 0.4, 0.75, [(where, 14, True, ACCENT)])
    bullets(s, x + 0.2, 3.9, cw - 0.4, 2.75, body, size=14, space=8)
d.save()
