# 2 案
s, top = page(prs, "再編の案",
              "利用の多い東線は残し、少ない便は予約の乗合の車(デマンド)に置き換える。", 3)
cw = (W - 2 * M - 2 * 20) / 3
cols = [
    ("東線", "残す", "1日 24便のまま", ["3路線で最も利用が多い(1便 6.1人)", "今の時刻表を変えない"]),
    ("西線", "減らして病院へ", "1日 18便 → 12便", ["1便 3.2人。便を絞り、赤字の最も大きい路線を軽くする",
                                          "経路を病院に寄せ、通院に使える線にする"]),
    ("山手線", "デマンドに替える", "1日 10便 → 予約の乗合", ["1便 1.4人。決まった時刻に空で走る便をやめる",
                                              "予約があるときだけ走る"]),
]
for i, (name, verb, change, pts) in enumerate(cols):
    x = M + i * (cw + 20)
    rect(s, x, top, cw, 36, ACC if i != 1 else ACC)
    text(s, x + 12, top, cw - 24, 36, [[(name, {"size": 16, "bold": True, "color": WHITE}),
                                        ("  " + verb, {"size": 14, "color": WHITE})]], anchor=MSO_ANCHOR.MIDDLE)
    text(s, x, top + 44, cw, 28, [(change, {"size": 16, "bold": True, "color": ACC})])
    bullets(s, x, top + 76, cw, 110, pts, size=13)
yd = top + 200
rect(s, M, yd, W - 2 * M, 160, ACC_L)
text(s, M + 16, yd + 10, 400, 22, [("デマンドの見込み(山手線の代わり)", {"size": 14, "bold": True, "color": ACC})])
kw = (W - 2 * M - 32) / 3
for i, (lab, big, unit) in enumerate([("予約", "30", "回/日"), ("費用", "1,100", "万円/年"), ("待ち時間", "25", "分(平均)")]):
    x = M + 16 + i * kw
    text(s, x, yd + 44, kw - 10, 20, [(lab, {"size": 12, "color": SUB, "bold": True})])
    text(s, x, yd + 64, kw - 10, 44, [[(big, {"size": 30, "bold": True, "color": ACC}), (" " + unit, {"size": 14, "color": ACC})]])
text(s, M + 16, yd + 116, W - 2 * M - 32, 40,
     [("山手線の赤字 年 1,750万円に対し、デマンドの費用は 年 1,100万円。", {"size": 14})])

