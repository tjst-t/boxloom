# 3. 試行と心配
s = d.content("試行は2階・140人・3か月。火曜の席の不足を先に手当て",
              "決めてほしいのは試行を始めること。全フロアに広げるかは試行の結果を見て別に決める。")
cw = (W - 2 * M - 0.6) / 3
y = 2.0
card(s, M, y, cw, 2.55, "火曜に席が足りるか",
     ["試算 76% × 140人 = 106人", "2階の席は100で、6人分足りない", "対策:火曜は集中の席も通常に使う・在宅の曜日を部署で分ける"],
     size=13, bar=ACCENT)
card(s, M + cw + 0.3, y, cw, 2.55, "紙の書類の置き場所",
     ["決まった席が無くなると書類を置けない", "対策:個人の鍵つきの棚と部署の共用の棚を用意する"],
     size=13)
card(s, M + 2 * (cw + 0.3), y, cw, 2.55, "部署の会話が減る",
     ["同じ部署が離れて座る", "対策:部署ごとに座る範囲の目安を決め、小部屋で打ち合わせる"],
     size=13)
text(s, M, 4.75, W - 2 * M, 0.4, [("評価の物差し(試行の前と後で比べる)", 15, True, NAVY)])
table(s, M, 5.2, W - 2 * M, 1.75, [
    ["物差し", "見るもの", "測り方"],
    ["席の空きを探す時間", "朝、席に着くまでの時間", "予約のシステムの記録と聞き取り"],
    ["満足度", "働きやすさ・会話のしやすさ", "試行の前と3か月後の調べ"],
    ["会議室の予約の取りやすさ", "希望の時刻に取れた割合", "会議室の予約の記録"],
], [3.2, 4.4, 4.53], size=13)
