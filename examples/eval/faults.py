def read(name):
    with open(os.path.join(HERE, name + ".bx.md"), encoding="utf-8") as f:
        return f.read()


def apply(src, old, new, fid):
    """old・new は文か、同じ長さの文の並び(1つの誤りで2か所を変えるとき)。"""
    olds = old if isinstance(old, list) else [old]
    news = new if isinstance(new, list) else [new]
    for o, n in zip(olds, news):
        if src.count(o) != 1:
            raise SystemExit("%s: 正しい版の文が1つに定まらない (%d)" % (fid, src.count(o)))
        src = src.replace(o, n)
    return src


def faulty(deck):
    src = read(deck)
    for fid, _, old, new, _ in FAULTS[deck]:
        src = apply(src, old, new, fid)
    return src


def main(argv):
    if len(argv) >= 2 and argv[0] == "--each":
        out = argv[1]
        os.makedirs(out, exist_ok=True)
        for deck, faults in FAULTS.items():
            base = read(deck)
            for fid, _, old, new, fix in faults:
                one = apply(base, old, new, fid)
                with open(os.path.join(out, "%s-%s.bx.md" % (deck, fid)), "w", encoding="utf-8") as f:
                    f.write(one)
                # 直し方の書いていない誤りは、hint に従うと正しい版に戻る
                fixed = apply(base, old, old if fix is None else fix, fid)
                if True:
                    with open(os.path.join(out, "%s-%s-fixed.bx.md" % (deck, fid)), "w", encoding="utf-8") as f:
                        f.write(fixed)
        return
    for deck in FAULTS:
        with open(os.path.join(HERE, deck + "-faulty.bx.md"), "w", encoding="utf-8") as f:
            f.write(faulty(deck))


if __name__ == "__main__":
    main(sys.argv[1:])
