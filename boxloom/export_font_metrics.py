"""
Go移植版(boxloom)が使うフォント計測テーブルを生成するスクリプト。

Go側は golang.org/x/image のようなフォント解析ライブラリを一切使わない
(このサンドボックスではgolang.org/x/imageすら取得できないネットワークポリシーだったため、
その場しのぎではなく「そもそもGoランタイムにフォント解析ライブラリを持たせない」
という設計に倒した)。

代わりに、信頼できるPillowでの実測を一度だけ行い、「1em(=フォントサイズ1pt)あたりの
グリフ幅の比率」をコードポイントごとにテーブル化してGoのソースコードに埋め込む。
TrueTypeのグリフ幅はフォントサイズに比例する(unitsPerEmに対する相対値)ので、
この比率さえ分かればGo側はフォントファイルを一切読まずに任意サイズでの幅を計算できる。

カバーする文字集合は、実際にboxloom側のデモコンテンツ(main.go)が使う文字列に
含まれる文字 + ASCII印字可能文字のみ。テーブルにない文字が来た場合、Go側は
「全角相当(1.0em)」にフォールバックする、という割り切りをmain.go側で明示する。
"""

import json
from PIL import ImageFont

FONT_PATH = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
FONT_PATH_BOLD = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
REF_SIZE = 1000  # 基準ピクセルサイズ。この大きさで測った幅をREF_SIZEで割ればem比率になる。

# boxloom/main.go のデモコンテンツに実際に登場する文字列(日本語部分)。
# ここに無い文字が実行時に出てきても落ちないよう、Go側ではフォールバック値を使う。
CONTENT_STRINGS = [
    "ボード世代ごとのランタイム選択肢と利用可能期間(架空のデモ)",
    "boxloom: v11(Python)をGoへ移植。box_engine.pyの箱配置アルゴリズムと"
    "意味役割名によるテーマ分離をそのまま踏襲",
    "boxloom: 自作エンジン + ブルー基調の明るいテーマ(内容は一切変更していない)",
    "ランタイム サポート有", "ランタイム サポート無", "ハードウェア サポート無",
    "26/9", "現在", "27/10", "Loom 3", "28/8", "Loom 4(予)",
    "29/12", "Board A・Store X", "31/2", "Board B(予)", "31/6", "Loom 5(予)",
    "31/10", "OS 22", "34/11", "OS 25",
    "★ 28/5 ライセンス更新", "★ 31/5 ライセンス更新",
    "第1世代\nBoard A\n120台\nStore X",
    "第2世代\nBoard B\n240台\nStore Y",
    "第2世代\nBoard C\n80台\nStore Y",
    "固定版", "定額版",
    "Loom 2", "Loom 3", "Loom 2/3", "(Loom 3)", "Weft OS 22", "Loom 3→4→5", "Loom 4", "Loom 5",
    "内部利用のみ、外部保守", "内部+外部利用", "延長要確認",
    "Store XはLoom 4非対応のため移行先になり得ない",
    "サポート対象", "ベンダーのサポート可否は要協議",
    "外部向け第2世代はセキュリティ要件で\nLoom 4化が必須(デモ)",
    "ここまでに全利用者を\nBoard B/Cへ移行予定(デモ)",
    "保守不可ならBoard C移行が要るが、\n増設/移行の期間が不足(デモ)",
    "ベンダー:27/6までLoom対応\n開発元:27/8にLoom 5公開予定(デモ)",
    "Board B保守延長予定(デモ)",
    "Boxloom デモ", "v12(Go移植/boxloom)",
]

chars = set(" ")
for s in CONTENT_STRINGS:
    chars.update(s)
for cp in range(0x20, 0x7F):  # ASCII印字可能文字も確実にカバー
    chars.add(chr(cp))

font_reg = ImageFont.truetype(FONT_PATH, size=REF_SIZE)
font_bold = ImageFont.truetype(FONT_PATH_BOLD, size=REF_SIZE)

table_reg = {}
table_bold = {}
for ch in sorted(chars):
    table_reg[ch] = round(font_reg.getlength(ch) / REF_SIZE, 6)
    table_bold[ch] = round(font_bold.getlength(ch) / REF_SIZE, 6)

print(f"covered {len(chars)} distinct characters")

with open("metrics_data.json", "w", encoding="utf-8") as f:
    json.dump({"regular": table_reg, "bold": table_bold}, f, ensure_ascii=False, indent=0)

print("wrote metrics_data.json")


def write_go_table(f, name, table):
    f.write(f"var {name} = map[rune]float64{{\n")
    for ch in sorted(table, key=ord):
        f.write(f"\t{ord(ch)}: {table[ch]!r}, // {ch!r}\n")
    f.write("}\n")


with open("metrics_gen.go", "w", encoding="utf-8") as f:
    f.write("// Code generated by export_font_metrics.py. DO NOT EDIT BY HAND.\n")
    f.write("// Pillowで実測した「1emあたりのグリフ幅」のルックアップテーブル。\n")
    f.write("// キーはUnicodeコードポイント、値は advance_px / font_size_px の比率。\n")
    f.write("package main\n\n")
    write_go_table(f, "glyphWidthRegular", table_reg)
    f.write("\n")
    write_go_table(f, "glyphWidthBold", table_bold)

print("wrote metrics_gen.go")
